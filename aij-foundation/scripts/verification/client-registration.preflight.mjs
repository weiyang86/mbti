import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const queue = JSON.parse(readFileSync("docs/planning/CODING_QUEUE.json", "utf8"));
const snapshot = readFileSync(queue.continuousQueueRun.snapshot);
const baseline = JSON.parse(readFileSync(".artifacts/continuous/2026-10-31-to-G19/AF-083-baseline.json", "utf8"));
assert.equal(createHash("sha256").update(snapshot).digest("hex"), queue.continuousQueueRun.snapshotSha256);
assert.equal(queue.activeRun.scopeSnapshotSha256, queue.continuousQueueRun.snapshotSha256);
assert.equal(queue.status, "CONTINUOUS_TO_G19_IN_PROGRESS");
assert.equal(queue.activeRun.batch, "NEXT-13");
assert.equal(queue.activeRun.currentCard, "G5-01/AF-083");
assert.equal(queue.formalTaskIdAssignments.batch, "NEXT-13");
assert.equal(queue.formalTaskIdAssignments.ids["G5-01"], "AF-083");
assert.equal(queue.formalTaskIdAssignmentsHistory.filter(item => item.ids?.["G5-01"] === "AF-083").length, 1);
assert.equal(queue.taskExecutions.filter(item => item.formalTaskId === "AF-083").length, 1);
assert.equal(queue.taskExecutions.filter(item => item.alias === "G5-01").length, 1);
const g4 = queue.taskExecutions.filter(item => ["AF-035", "AF-036", "AF-037", "AF-038"].includes(item.formalTaskId));
assert.equal(g4.length, 4);
assert.ok(g4.every(item => item.status === "CODE_VERIFIED"));
const notification = queue.taskExecutions.find(item => item.formalTaskId === "AF-082");
assert.equal(notification?.status, "CODE_VERIFIED");
assert.equal(notification?.git?.remoteReadback, notification?.git?.commit);
assert.equal(notification?.ownerAcceptance, "PENDING_UNIFIED_OWNER_CHECK");
const current = queue.taskExecutions.find(item => item.formalTaskId === "AF-083");
assert.equal(current?.status, "IN_PROGRESS");
assert.deepEqual(current?.authorization?.prerequisites, ["NEXT-03 CODE_VERIFIED", "NEXT-12 CODE_VERIFIED"]);
assert.equal(current?.baseline?.branch, "dev");
assert.equal(current?.baseline?.head, baseline.head);
assert.equal(baseline.formalTaskId, "AF-083");
assert.equal(baseline.branch, "dev");
assert.equal(execFileSync("git", ["--no-optional-locks", "rev-parse", "--abbrev-ref", "HEAD"], { encoding: "utf8" }).trim(), "dev");
assert.equal(execFileSync("git", ["--no-optional-locks", "rev-parse", "HEAD"], { encoding: "utf8" }).trim(), baseline.head);
console.log("AF-083 assignment, frozen queue, G4/NEXT-12 code dependencies and saved dev baseline are intact; owner acceptance remains pending.");
