// Integrity checks supplement real harness assertions; JSON assertions are not proof.
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { lstat, readFile, realpath } from "node:fs/promises";
import { resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { repositoryRoot, sha256 } from "./workbench-sdk-target-consumer.mjs";

export const requiredNativeCases = ["desktop-workbench-submit", "desktop-workbench-read", "desktop-consumer-read", "mobile390-workbench-read", "mobile390-consumer-read",
  "anonymous", "no-permission", "other-member", "scope-change", "role-change", "session-change", "blur", "document-hidden", "unmount"];
export const requiredSourcePaths = [
  "apps/web/app/client/ai/page.tsx", "apps/web/app/components/client-ai-workbench.tsx", "apps/web/app/components/client-ai-workbench-state.mjs",
  "packages/sdk/src/index.ts", "packages/contracts/src/index.ts", "packages/sdk/dist/index.mjs", "packages/contracts/dist/index.mjs",
  "packages/sdk/package.json", "packages/contracts/package.json", "apps/api/src/plugins/aij-ai/ai-center-run.service.ts",
  "apps/api/src/plugins/aij-ai/ai-center-provider.ts",
  "apps/api/dist/plugins/aij-ai/ai-center-run.service.js", "apps/api/dist/plugins/aij-ai/ai-center-provider.js",
  "scripts/verification/workbench-sdk-target-consumer.mjs", "scripts/verification/workbench-sdk-target-live.test.mjs", "scripts/verification/workbench-sdk-target-proof.mjs",
  "scripts/verification/workbench-sdk-target-root.mjs", "scripts/verification/workbench-sdk-target-host.mjs",
  "scripts/verification/workbench-sdk-target-native-driver.mjs", "scripts/verification/w22-native-chrome.mjs", "scripts/verification/w21-native-browser.mjs", "scripts/verification/workbench-sdk-target-runtime.mjs",
  "scripts/verification/workbench-sdk-target-adapter.mjs", "scripts/verification/workbench-sdk-target-adapter-evidence.mjs"
];
const hash = value => typeof value === "string" && /^[a-f0-9]{64}$/.test(value);
const id = value => typeof value === "string" && /^[A-Za-z0-9_-]{1,128}$/.test(value);
const within = (root, p) => p.startsWith(root + sep);

/** Raw evidence files must have been generated by the adapter from real operations.
 * This checker cannot authenticate a screenshot's origin or manufacture a receipt.
 * @param {object} proof metadata produced by the root harness after assertions
 */
export async function checkTargetProof(proof, { root = repositoryRoot, now = Date.now() } = {}) {
  assert.equal(proof?.schemaVersion, 1, "AF191_PROOF_SCHEMA_REQUIRED");
  assert.equal(proof.task, "AF-191"); assert.equal(proof.stage, "ROOT_ASSERTED");
  assert(id(proof.acceptanceId) && proof.approvedLeaseTask === "AF-191", "AF191_APPROVED_LEASE_REQUIRED");
  assert(id(proof.runId) && id(proof.workspaceId), "AF191_REAL_RUN_REQUIRED");
  assert.match(proof.sourceCommit, /^[a-f0-9]{40}$/);
  const start = Date.parse(proof.startedAt), end = Date.parse(proof.finishedAt);
  assert(Number.isFinite(start) && Number.isFinite(end) && start <= end && end <= now + 1000 && now - end < 24 * 3600000, "AF191_FRESH_RUN_REQUIRED");
  assert.deepEqual(proof.counters, { runs: 1, jobs: 1, traces: 1, upstream: 1, submits: 1 }, "AF191_EXACTLY_ONCE_REQUIRED");
  assert.deepEqual(proof.refusals, { anonymous: 401, noPermission: 403, otherMember: 404 }, "AF191_API_REFUSALS_REQUIRED");
  assert.equal(proof.transport, "AiCenterHttpTransport:owned-loopback");
  assert.equal(proof.vendorReadiness, "NOT_PROVEN_SYNTHETIC");
  assert.equal(proof.ownerAcceptance, "PENDING");
  assert.equal(proof.closed?.applicationPools, 0); assert.equal(proof.closed?.ownedSockets, 0); assert.equal(proof.closed?.consumerRemoved, true);
  assert(proof.packages && hash(proof.packages.sdk?.sha256) && hash(proof.packages.contracts?.sha256) && hash(proof.packages.lockSha256), "AF191_PACKAGE_HASHES_REQUIRED");
  assert(proof.packages.outsideRepository === true && proof.packages.realInstall === true);
  assert.deepEqual(proof.packages.matrix, ["esm", "cjs", "esm-types", "cjs-types", "browser-importmap"]);
  const sources = new Set(), native = new Set(), kinds = new Set(), paths = new Set(), raw = new Map();
  assert(Array.isArray(proof.files) && proof.files.length > 0, "AF191_EVIDENCE_FILES_REQUIRED");
  root = await realpath(root);
  if (root === await realpath(repositoryRoot)) assert.equal(proof.sourceCommit, execFileSync("git", ["rev-parse", "HEAD"], { cwd: root, encoding: "utf8" }).trim(), "AF191_HEAD_CHANGED");
  for (const f of proof.files) {
    assert(typeof f.path === "string" && !f.path.split(/[\\/]/).some(p => p === ".." || p === ".") && hash(f.sha256), "AF191_EVIDENCE_REFERENCE_INVALID");
    const path = resolve(root, f.path);
    assert(within(root, path) && !paths.has(path), "AF191_EVIDENCE_PATH_INVALID"); paths.add(path);
    assert.equal(await realpath(path), path, "AF191_EVIDENCE_SYMLINK_REJECTED");
    const stat = await lstat(path); assert(stat.isFile() && stat.size > 0, "AF191_EVIDENCE_EMPTY");
    const bytes = await readFile(path); assert.equal(sha256(bytes), f.sha256, "AF191_EVIDENCE_HASH_MISMATCH");
    if (f.kind === "source") sources.add(f.path);
    else {
      assert(f.path.startsWith(".artifacts/"), "AF191_PRIVATE_ARTIFACT_REQUIRED");
      assert.equal(f.acceptanceId, proof.acceptanceId); assert.equal(f.task, "AF-191");
      assert(Date.parse(f.observedAt) >= start && Date.parse(f.observedAt) <= end, "AF191_RECEIPT_TIME_INVALID");
      kinds.add(f.kind);
      if (f.kind === "native") {
        assert(requiredNativeCases.includes(f.case), "AF191_NATIVE_CASE_INVALID");
        assert.equal(f.runId, proof.runId); assert.equal(f.native, true);
        assert.equal(f.viewportWidth, f.case.startsWith("mobile390") ? 390 : 1440);
        assert(bytes.length > 100 && bytes.subarray(0, 8).equals(Buffer.from([137,80,78,71,13,10,26,10])), "AF191_NATIVE_PNG_REQUIRED");
        assert(!native.has(f.case), "AF191_DUPLICATE_NATIVE_CASE"); native.add(f.case);
      } else if (["lease", "http", "pg", "package-install", "package-matrix", "native-receipts", "closed"].includes(f.kind)) {
        assert(!raw.has(f.kind), "AF191_DUPLICATE_RAW_KIND");
        const value = JSON.parse(bytes.toString("utf8")); assert.equal(value.task, "AF-191");
        assert.equal(value.acceptanceId ?? value.id, proof.acceptanceId); raw.set(f.kind, value);
      }
    }
  }
  for (const p of requiredSourcePaths) assert(sources.has(p), "AF191_CURRENT_SOURCE_HASH_MISSING:" + p);
  for (const c of requiredNativeCases) assert(native.has(c), "AF191_NATIVE_EVIDENCE_MISSING:" + c);
  for (const k of ["lease", "http", "pg", "package-install", "package-matrix", "native-receipts", "closed"]) assert(kinds.has(k), "AF191_RAW_EVIDENCE_MISSING:" + k);
  for (const name of ["sdk", "contracts"]) {
    const packed = proof.files.find(f => f.kind === "packed-" + name);
    assert(packed && packed.sha256 === proof.packages[name].sha256, "AF191_CURRENT_PACK_HASH_MISSING:" + name);
    const installed = proof.files.find(f => f.kind === "installed-" + name);
    const built = proof.files.find(f => f.kind === "source" && f.path === `packages/${name}/dist/index.mjs`);
    assert(installed && installed.sha256 === built.sha256, "AF191_INSTALLED_CURRENT_DIST_MISMATCH:" + name);
  }
  const lock = proof.files.find(f => f.kind === "install-lock");
  assert(lock && lock.sha256 === proof.packages.lockSha256, "AF191_INSTALL_LOCK_HASH_MISSING");
  const lease = raw.get("lease");
  assert.equal(lease.mode, "test"); assert.equal(lease.ready, true); assert(Date.parse(lease.createdAt) >= start);
  const http = raw.get("http"); assert.equal(http.runId, proof.runId); assert.equal(http.workspaceId, proof.workspaceId);
  assert(Array.isArray(http.responses), "AF191_ACTUAL_HTTP_RECEIPTS_REQUIRED");
  const posts = http.responses.filter(r => r.method === "POST" && r.path === "/client/ai/agents/general-text/runs");
  assert.equal(posts.length, 1); assert.equal(posts[0].status, 202);
  assert(http.responses.some(r => r.method === "GET" && r.path.startsWith("/client/ai/run-requests/") && r.actor === "owner" && r.status === 200 && hash(r.bodySha256)), "AF191_EXPLICIT_RESPONSE_LOSS_RECOVERY_GET_REQUIRED");
  for (const [actor, status] of [["owner", 200], ["anonymous", 401], ["no-permission", 403], ["other-member", 404]]) {
    assert(http.responses.some(r => r.method === "GET" && r.path === `/client/ai/runs/${proof.runId}` && r.actor === actor && r.status === status && hash(r.bodySha256)), "AF191_ACTUAL_HTTP_RECEIPT_MISSING:" + actor);
  }
  const pg = raw.get("pg"); assert.equal(pg.runId, proof.runId); assert.equal(pg.workspaceId, proof.workspaceId);
  assert.deepEqual(pg.before, { runs: 0, jobs: 0, traces: 0, upstream: 0, submits: 0 }); assert.deepEqual(pg.after, proof.counters);
  const install = raw.get("package-install"); assert.equal(install.command, "npm install --offline --ignore-scripts --no-audit --no-fund"); assert.equal(install.exitCode, 0);
  assert.equal(install.lockSha256, proof.packages.lockSha256);
  for (const name of ["sdk", "contracts"]) assert.equal(install.packages?.[name]?.sha256, proof.packages[name].sha256);
  assert(install.installedHashes && Object.keys(install.installedHashes).length > 5, "AF191_INSTALLED_GRAPH_HASHES_REQUIRED");
  for (const [installedPath, digest] of Object.entries(install.installedHashes)) {
    const match = /^node_modules\/@aij\/(sdk|contracts)\/(dist\/[A-Za-z0-9_./-]+|package\.json)$/.exec(installedPath);
    assert(match && !installedPath.split("/").includes("..") && hash(digest), "AF191_INSTALLED_GRAPH_PATH_INVALID");
    if (match[2] === "package.json") continue; // pnpm legitimately rewrites workspace ranges in the packed manifest.
    const current = resolve(root, "packages", match[1], match[2]);
    assert.equal(await realpath(current), current);
    assert.equal(sha256(await readFile(current)), digest, "AF191_INSTALLED_GRAPH_NOT_CURRENT:" + installedPath);
  }
  assert.deepEqual(raw.get("package-matrix").matrix, proof.packages.matrix);
  const receipts = raw.get("native-receipts"); assert.equal(receipts.driver, "orca-computer"); assert.equal(receipts.runId, proof.runId);
  assert(Array.isArray(receipts.receipts) && receipts.receipts.length === requiredNativeCases.length);
  for (const name of requiredNativeCases) {
    const receipt = receipts.receipts.find(r => r.case === name), screenshot = proof.files.find(f => f.kind === "native" && f.case === name);
    assert(receipt && receipt.native === true && receipt.screenshotSha256 === screenshot.sha256 && receipt.runId === proof.runId, "AF191_NATIVE_RECEIPT_MISMATCH:" + name);
    const status = { anonymous: 401, "no-permission": 403, "other-member": 404, "scope-change": 404, "role-change": 403, "session-change": 401 }[name];
    if (status) { assert.equal(receipt.apiStatus, status); assert.equal(receipt.privateContentCleared, true); }
  }
  const closed = raw.get("closed"); assert.equal(closed.applicationPools, 0); assert.equal(closed.ownedSockets, 0);
  return { status: "INTEGRITY_CHECKED", targetAcceptance: "REQUIRES_ROOT_REAL_HARNESS", ownerAcceptance: "PENDING" };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  assert(process.argv[2], "AF191_PROOF_FILE_REQUIRED");
  const result = await checkTargetProof(JSON.parse(await readFile(process.argv[2], "utf8")));
  process.stdout.write(JSON.stringify(result) + "\n");
}
