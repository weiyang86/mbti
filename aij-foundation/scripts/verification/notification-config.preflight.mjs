import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const queue = JSON.parse(readFileSync("docs/planning/CODING_QUEUE.json", "utf8"));
const snapshot = readFileSync(queue.activeRun.scopeSnapshot);
const baseline = JSON.parse(readFileSync(".artifacts/continuous/2026-10-31-to-G19/AF-082-baseline.json", "utf8"));
assert.equal(createHash("sha256").update(snapshot).digest("hex"), queue.activeRun.scopeSnapshotSha256);
assert.equal(queue.continuousQueueRun.snapshotSha256, queue.activeRun.scopeSnapshotSha256);
assert.equal(queue.status, "CONTINUOUS_TO_G19_IN_PROGRESS");
assert.equal(queue.activeRun.batch, "NEXT-12");
assert.equal(queue.activeRun.writer, "Codex");
assert.equal(queue.formalTaskIdAssignments.ids["G14-03"], "AF-082");
assert.equal(queue.formalTaskIdAssignmentsHistory.filter(item => item.ids?.["G14-03"] === "AF-082").length, 1);
assert.equal(queue.taskExecutions.filter(item => item.formalTaskId === "AF-082").length, 1);
const previous = queue.taskExecutions.find(item => item.formalTaskId === "AF-081");
assert.equal(previous?.status, "CODE_VERIFIED");
assert.equal(previous?.git?.commitSha, "f80a7eab54176ac126486db7bc58fcf1e4eb247f");
assert.equal(previous?.git?.remoteReadbackSha, previous?.git?.commitSha);
const current = queue.taskExecutions.find(item => item.formalTaskId === "AF-082");
assert.ok(["IN_PROGRESS", "CODE_VERIFIED"].includes(current?.status));
assert.equal(baseline.taskId, "AF-082");
assert.equal(baseline.branch, "dev");
assert.equal(baseline.head, "f80a7eab54176ac126486db7bc58fcf1e4eb247f");
assert.equal(baseline.originDev, baseline.head);
assert.equal(baseline.priorOwnerAcceptance, "PENDING_UNIFIED_OWNER_CHECK");
assert.equal(execFileSync("git", ["--no-optional-locks", "rev-parse", "--abbrev-ref", "HEAD"], { encoding: "utf8" }).trim(), "dev");
assert.equal(execFileSync("git", ["--no-optional-locks", "rev-parse", "HEAD"], { encoding: "utf8" }).trim(), baseline.head);
console.log("AF-082 assignment, frozen queue, AF-081 dependency and saved dev baseline are intact.");
